"""Generate a small vector outline once; no pixel analysis runs in the app."""
from collections import defaultdict
from pathlib import Path

from PIL import Image, ImageFilter


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "assets/images/branding/captain_splash_logo.png"
TARGET = ROOT / "lib/features/auth/splash/widgets/splash_logo_outline.dart"


def simplify(points, tolerance=0.75):
    if len(points) < 3:
        return points
    x0, y0 = points[0]
    x1, y1 = points[-1]
    dx, dy = x1 - x0, y1 - y0
    denominator = dx * dx + dy * dy
    distances = []
    for x, y in points[1:-1]:
        t = max(0, min(1, ((x - x0) * dx + (y - y0) * dy) / denominator)) if denominator else 0
        distances.append(((x - x0 - t * dx) ** 2 + (y - y0 - t * dy) ** 2) ** 0.5)
    maximum = max(distances)
    if maximum <= tolerance:
        return [points[0], points[-1]]
    index = distances.index(maximum) + 1
    return simplify(points[:index + 1], tolerance)[:-1] + simplify(points[index:], tolerance)


image = Image.open(SOURCE)
width = 280
height = round(width * image.height / image.width)
alpha = image.getchannel("A").resize((width, height)).filter(ImageFilter.MedianFilter(3))
pixels = alpha.load()


def solid(x, y):
    return 0 <= x < width and 0 <= y < height and pixels[x, y] >= 110


edges = defaultdict(list)
for y in range(height):
    for x in range(width):
        if not solid(x, y):
            continue
        if not solid(x, y - 1):
            edges[(x, y)].append((x + 1, y))
        if not solid(x + 1, y):
            edges[(x + 1, y)].append((x + 1, y + 1))
        if not solid(x, y + 1):
            edges[(x + 1, y + 1)].append((x, y + 1))
        if not solid(x - 1, y):
            edges[(x, y + 1)].append((x, y))

rings = []
while edges:
    start = next(iter(edges))
    ring = [start]
    current = start
    while current in edges:
        following = edges[current].pop()
        if not edges[current]:
            del edges[current]
        ring.append(following)
        current = following
        if current == start:
            break
    if len(ring) > 100:
        rings.append(ring)

# The largest outer component follows the captain, map, car and wordmark.
ring = max(rings, key=len)[:-1]
start_index = min(range(len(ring)), key=lambda i: ring[i][1])
ring = ring[start_index:] + ring[:start_index]
ring.append(ring[0])
outline = simplify(ring)
commands = []
for index, (x, y) in enumerate(outline):
    method = "moveTo" if index == 0 else "lineTo"
    commands.append(f"    ..{method}({x / width:.5f}, {y / height:.5f})")
TARGET.write_text(
    "// Generated by tool/branding/generate_splash_outline.py from the logo alpha.\n"
    "// Normalized coordinates; image fitting is applied by SplashTracePainter.\n"
    "import 'dart:ui';\n\n"
    "Path createSplashLogoOutline() => Path()\n"
    + "\n".join(commands) + "\n    ..close();\n",
    encoding="utf-8",
)
print(f"Wrote {len(outline)} outline points to {TARGET}")
